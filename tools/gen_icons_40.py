#!/usr/bin/env python3
"""生成 40x40 苹果图标"""
import struct, os

def _crc16(d):
    c = 0xFFFF
    for b in d:
        c ^= b << 8
        for _ in range(8):
            c = ((c << 1) ^ 0x1021) & 0xFFFF if c & 0x8000 else (c << 1) & 0xFFFF
    return c

def rows_to_mask(rows):
    mask = bytearray()
    for row in rows:
        for byte_idx in range(5):  # 40 bits = 5 bytes
            val = 0
            for bit in range(8):
                px = byte_idx * 8 + bit
                if px < len(row) and row[px] == "1":
                    val |= 1 << (7 - bit)
            mask.append(val)
    return mask

def write_icon(path, fg565, rows):
    W, H = 40, 40
    BG = 0x10A2
    mask = rows_to_mask(rows)
    crc = _crc16(mask)
    header = struct.pack("<HHHHH", W, H, fg565, BG, crc)
    with open(path, "wb") as f:
        f.write(header)
        f.write(mask)
    print(f"  {os.path.basename(path)}: 40x40 fg=0x{fg565:04X} crc=0x{crc:04X} ({len(header)+len(mask)}B)")

