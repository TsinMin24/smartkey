#!/usr/bin/env python3
"""生成 16x16 RGB565 全色图标（displayio，256色调色板 ≈ 2KB×5）"""
import os

def make_rgb565(r, g, b):
    return (r >> 3) << 11 | (g >> 2) << 5 | (b >> 3)

BG = make_rgb565(26, 26, 26)

def write_icon(path, rows, colors):
    W, H = 16, 16
    data = bytearray(W * H * 2)
    for y in range(H):
        row = rows[y] if y < len(rows) else "0" * W
        for x in range(W):
            ch = row[x] if x < len(row) else "0"
            if ch in colors:
                r, g, b = colors[ch]
                c = make_rgb565(r, g, b)
            else:
                c = BG
            off = (y * W + x) * 2
            data[off] = c & 0xFF
            data[off + 1] = c >> 8
    with open(path, "wb") as f:
        f.write(data)
    print(f"  {os.path.basename(path)}: {len(data)}B")

