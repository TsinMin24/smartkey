#!/usr/bin/env python3
"""生成 slot 2~5 的图标二进制数据"""
import struct
import os


def _crc16(data):
    crc = 0xFFFF
    for b in data:
        crc ^= b << 8
        for _ in range(8):
            if crc & 0x8000:
                crc = ((crc << 1) ^ 0x1021) & 0xFFFF
            else:
                crc = (crc << 1) & 0xFFFF
    return crc


def rows_to_mask(rows):
    mask = bytearray()
    for row in rows:
        for byte_idx in range(4):  # 32 bits = 4 bytes
            val = 0
            for bit in range(8):
                px = byte_idx * 8 + bit
                if px < len(row) and row[px] == "1":
                    val |= 1 << (7 - bit)
            mask.append(val)
    return mask


def write_icon(path, w, h, fg565, bg565, rows):
    assert len(rows) == h
    for i, row in enumerate(rows):
        assert len(row) == w, f"Row {i}: got {len(row)}, expected {w}"
    mask = rows_to_mask(rows)
    crc = _crc16(mask)
    header = struct.pack("<HHHHH", w, h, fg565, bg565, crc)
    with open(path, "wb") as f:
        f.write(header)
        f.write(mask)
    print(f"  {os.path.basename(path)}: {w}x{h} fg=0x{fg565:04X} bg=0x{bg565:04X} crc=0x{crc:04X} ({len(header)+len(mask)}B)")


